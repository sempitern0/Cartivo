import {test,expect} from '@playwright/test';
test('minimal home and real worker lifecycle',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');
 await expect(page.getByRole('button',{name:'Elegir juego'})).toBeEnabled();
 await expect(page.getByRole('button',{name:'Iniciar prueba'})).not.toBeVisible();
 await page.locator('summary').click();
 await page.getByRole('button',{name:'Iniciar prueba'}).click();
 await expect(page.getByRole('status')).toHaveText('En marcha');
 await page.getByRole('button',{name:'Pausar',exact:true}).click();
 await expect(page.getByRole('status')).toHaveText('En pausa');
 await page.getByRole('button',{name:'Reanudar'}).click();
 await expect(page.getByRole('status')).toHaveText('En marcha');
 await page.getByRole('button',{name:'Finalizar'}).click();
 await expect(page.getByRole('status')).toHaveText('Finalizada');
 await page.getByRole('button',{name:'Nueva sesión'}).click();
 await expect(page.getByRole('status')).toHaveText('Preparada');
 await page.setViewportSize({width:360,height:780});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:'test-results/cartivo-mobile.png',fullPage:true});
 expect(errors).toEqual([]);
});
