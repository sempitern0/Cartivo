// Builds cores/pcsx-rearmed (PlayStation) to standalone WebAssembly and
// records what was built. Run in CI only, on explicit request
// (.github/workflows/core-pcsx-rearmed.yml). Needs emcc from
// cores/pcsx-rearmed/toolchain.json. cores/pcsx-rearmed/sources.txt is
// upstream's libretro target (Makefile.libretro) for a build without dynarec,
// threads, CHD or physical CD-ROM, with libretro's VFS (the discs are read
// through the host) and the in-tree miniz instead of Emscripten's zlib port.
// The Cartivo bridge (src/cartivo.c) drives that frontend.
//   node tools/build-pcsx-rearmed.mjs           build + dist/, manifest, sbom
//   node tools/build-pcsx-rearmed.mjs --verify  build into a temp dir and compare
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const core = join(root, "cores/pcsx-rearmed");
const work = join(core, "build");
const verify = process.argv.includes("--verify");
const pins = JSON.parse(readFileSync(join(core, "toolchain.json"), "utf8"));
const run = (cmd, args, opts = {}) =>
  (execFileSync(cmd, args, { encoding: "utf8", stdio: ["ignore", "pipe", "inherit"], ...opts }) ?? "").trim();
const sha256 = (file) =>
  createHash("sha256").update(readFileSync(file)).digest("hex");

const emcc = run("emcc", ["--version"]).split("\n")[0];
if (!emcc.includes(` ${pins.emsdk.version} `))
  throw Error(`emcc ${pins.emsdk.version} requerido; encontrado: ${emcc}`);

mkdirSync(work, { recursive: true });
const pcsx = join(work, "pcsx_rearmed");
const { repository, commit } = pins.pcsxRearmed;
// Fetch exactly the pinned commit (no submodules: lightrec and the CHD
// dependencies are not built).
if (!existsSync(join(pcsx, ".git"))) {
  run("git", ["init", "-q", pcsx]);
  run("git", ["-C", pcsx, "fetch", "-q", "--depth", "1", repository, commit], { stdio: "inherit" });
  run("git", ["-C", pcsx, "-c", "advice.detachedHead=false", "checkout", "-q", "FETCH_HEAD"]);
}
const head = run("git", ["-C", pcsx, "rev-parse", "HEAD"]);
if (head !== commit) throw Error(`PCSX-ReARMed: ${head} no es el commit fijado ${commit}`);
// Generated by upstream's Makefile from `git describe --always`; it also
// tags save states ("STv4 PCSXra <rev>").
writeFileSync(join(pcsx, "include/revision.h"), `#define REV "${commit.slice(0, 7)}"\n`);

const sources = readFileSync(join(core, "sources.txt"), "utf8").split("\n").filter(Boolean);
// The flags of Makefile/Makefile.libretro (emscripten platform, release):
// interpreter only, software GPU (gpu_neon's portable SIMD path on wasm
// SIMD), no mmap, no dylib or sockets; plus libretro VFS and fixed paths.
const flags = [
  "-O3", "-DNDEBUG", "-ffast-math", "-msimd128",
  `-DGIT_VERSION=" ${commit.slice(0, 7)}"`,
  "-DP_HAVE_MMAP=0", "-DP_HAVE_POSIX_MEMALIGN=1", "-DDISABLE_MEM_LUTS=0",
  "-DDRC_DISABLE", "-DGPU_NEON", "-DUSE_MINIZ", "-DUSE_LIBRETRO_VFS", "-DHAVE_LIBRETRO",
  "-DNO_FRONTEND", "-DNO_DYLIB", "-DNO_SOCKET",
  `-I${join(pcsx, "include")}`, `-I${join(pcsx, "deps/libretro-common/include")}`,
  `-I${join(pcsx, "deps/libchdr/deps/miniz-3.1.2")}`,
  `-ffile-prefix-map=${pcsx}=/pcsx_rearmed`, `-ffile-prefix-map=${root}=/cartivo`,
];
// Upstream's per-file flags.
const fileFlags = {
  "frontend/main.c": ["-DBUILTIN_GPU=neon"],
  "libpcsxcore/misc.c": ["-DBUILTIN_GPU=neon"],
  "plugins/dfsound/out.c": ["-DHAVE_LIBRETRO"],
  "plugins/gpu_neon/psx_gpu_if.c": ["-DNEON_BUILD", "-DTEXTURE_CACHE_4BPP", "-DTEXTURE_CACHE_8BPP", "-DSIMD_BUILD"],
  // SSE intrinsics, translated by Emscripten to wasm SIMD.
  "plugins/gpu_neon/psx_gpu/psx_gpu_simd.c": ["-DSIMD_BUILD", "-msse4.2"],
};
const objects = join(work, "obj");
rmSync(objects, { recursive: true, force: true });
mkdirSync(objects, { recursive: true });
const built = [];
for (const [i, source] of sources.entries()) {
  const object = join(objects, `${String(i).padStart(3, "0")}.o`);
  run("emcc", [...flags, ...(fileFlags[source] ?? []), "-w", "-c", join(pcsx, source), "-o", object], { stdio: "inherit" });
  built.push(object);
}
run("emcc", [...flags, "-Wall", "-Wextra", "-c", join(core, "src/cartivo.c"), "-o", join(objects, "cartivo.o")], { stdio: "inherit" });

const exports = [
  "malloc", "free", "cartivo_create", "cartivo_free", "cartivo_reset",
  "cartivo_save_size", "cartivo_load_save", "cartivo_save", "cartivo_set_input",
  "cartivo_frames", "cartivo_pixels", "cartivo_audio",
  "cartivo_state_size", "cartivo_save_state", "cartivo_load_state",
  "cartivo_frame_rate", "cartivo_set_analog",
];
const out = verify ? mkdtempSync(join(tmpdir(), "pcsx-")) : join(core, "dist");
if (!verify) rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
const wasm = join(out, "pcsx-rearmed.wasm");
run("emcc", [
  "-O3", "--no-entry", "-msimd128",
  "-sSTANDALONE_WASM=1", "-sFILESYSTEM=0", "-sALLOW_MEMORY_GROWTH=1",
  // 2 MiB of RAM, 1 MiB of VRAM, the SPU and a 4.4 MB state buffer.
  "-sINITIAL_MEMORY=64MB", "-sSTACK_SIZE=1MB",
  `-sEXPORTED_FUNCTIONS=${exports.map((e) => `_${e}`).join(",")}`,
  ...built, join(objects, "cartivo.o"),
  "-o", wasm,
], { stdio: "inherit" });

// Fail here, not in the player, if the module needs a host function that
// packages/adapters/src/wasm-host.ts does not offer.
const offered = new Set([
  "env.emscripten_notify_memory_growth", "env.__syscall_ftruncate64", "env.__syscall_getdents64",
  "env.cartivo_vfs_open", "env.cartivo_vfs_size", "env.cartivo_vfs_read", "env.cartivo_vfs_close",
  ...["clock_time_get", "fd_write", "fd_read", "fd_close", "fd_seek", "environ_sizes_get",
    "environ_get", "args_sizes_get", "args_get", "proc_exit"].map((n) => `wasi_snapshot_preview1.${n}`),
]);
const imports = WebAssembly.Module.imports(new WebAssembly.Module(readFileSync(wasm)))
  .map(({ module, name }) => `${module}.${name}`);
const missing = imports.filter((i) => !offered.has(i));
if (missing.length) throw Error(`Imports sin host en Cartivo: ${missing.join(", ")}`);
const files = [{ path: "dist/pcsx-rearmed.wasm", sha256: sha256(wasm) }];

if (verify) {
  const manifest = JSON.parse(readFileSync(join(core, "manifest.json"), "utf8"));
  if (JSON.stringify(manifest.files) !== JSON.stringify(files)) {
    console.error("Build no reproducible.\nVersionado:", manifest.files, "\nNuevo:", files);
    process.exit(1);
  }
  console.log("Build reproducible:", files[0].sha256.slice(0, 12));
  process.exit(0);
}

const emscripten = "https://github.com/emscripten-core/emscripten";
const sbom = [
  { name: "PCSX-ReARMed (libpcsxcore with HLE BIOS, libretro frontend, gpulib, gpu_neon, dfsound)", version: commit, license: "GPL-2.0-or-later", repository },
  { name: "miniz 3.1.2 (deps/libchdr/deps)", version: commit, license: "MIT", repository },
  { name: "libretro API header and libretro-common", version: commit, license: "MIT", repository },
  { name: "Emscripten system libraries", version: pins.emsdk.version, license: "MIT OR NCSA", repository: emscripten },
  { name: "musl libc (Emscripten)", version: pins.emsdk.version, license: "MIT", repository: emscripten },
  { name: "compiler-rt (Emscripten)", version: pins.emsdk.version, license: "Apache-2.0 WITH LLVM-exception", repository: emscripten },
  { name: "dlmalloc (Emscripten)", version: pins.emsdk.version, license: "CC0-1.0", repository: emscripten },
];
writeFileSync(join(core, "sbom.json"), JSON.stringify(sbom, null, 2) + "\n");

const manifest = {
  id: "pcsx-rearmed-ps1-wasm",
  engine: "WebAssembly (standalone)",
  upstream: { name: "PCSX-ReARMed", ...pins.pcsxRearmed },
  toolchain: { emcc, emsdk: `${pins.emsdk.version} (${pins.emsdk.commit})` },
  platforms: ["PlayStation"],
  biosRequired: false,
  bios: "None: the core's own HLE BIOS (libpcsxcore/psxbios.c) is forced; no system directory is offered, so Sony's BIOS is never looked for",
  sources: sources.length,
  patchedFiles: [],
  exports,
  imports,
  dependencies: sbom.length,
  files,
};
writeFileSync(join(core, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");
console.log(`PCSX-ReARMed ${commit.slice(0, 7)} → ${files.map((f) => `${f.path} ${f.sha256.slice(0, 12)}`).join(", ")}`);
