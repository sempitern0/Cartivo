// Builds cores/sameboy to standalone WebAssembly and records what was built.
// Run in CI only, on explicit request (.github/workflows/core-sameboy.yml).
// Needs emcc from cores/sameboy/toolchain.json on PATH, plus gcc, cmake,
// bison and libpng for rgbds (which assembles SameBoy's free boot ROMs).
//   node tools/build-sameboy.mjs           build + write dist/, manifest, sbom
//   node tools/build-sameboy.mjs --verify  build into a temp dir and compare
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const core = join(root, "cores/sameboy");
const work = join(core, "build");
const verify = process.argv.includes("--verify");
const pins = JSON.parse(readFileSync(join(core, "toolchain.json"), "utf8"));
const run = (cmd, args, opts = {}) =>
  (execFileSync(cmd, args, { encoding: "utf8", stdio: ["ignore", "pipe", "inherit"], ...opts }) ?? "").trim();
const sha256 = (file) =>
  createHash("sha256").update(readFileSync(file)).digest("hex");

/** Shallow clone at a tag and refuse anything but the pinned commit. */
function checkout(name, { repository, tag, commit }) {
  const dir = join(work, name);
  if (!existsSync(join(dir, ".git")))
    run("git", ["-c", "advice.detachedHead=false", "clone", "--depth", "1", "--branch", tag, repository, dir], { stdio: "inherit" });
  const head = run("git", ["-C", dir, "rev-parse", "HEAD"]);
  if (head !== commit) throw Error(`${name}: ${head} no es el commit fijado ${commit}`);
  return dir;
}

const emcc = run("emcc", ["--version"]).split("\n")[0];
if (!emcc.includes(` ${pins.emsdk.version} `))
  throw Error(`emcc ${pins.emsdk.version} requerido; encontrado: ${emcc}`);

mkdirSync(work, { recursive: true });
const sameboy = checkout("sameboy", pins.sameboy);
const rgbds = checkout("rgbds", pins.rgbds);

// rgbds (host tool) → SameBoy boot ROMs from their own assembly sources.
run("cmake", ["-S", rgbds, "-B", join(rgbds, "build"), "-DCMAKE_BUILD_TYPE=Release"], { stdio: "inherit" });
run("cmake", ["--build", join(rgbds, "build"), "-j4"], { stdio: "inherit" });
run("make", ["-C", sameboy, "bootroms", `RGBDS=${rgbds}/`, "-j4"], { stdio: "inherit" });
const bootRoms = ["dmg_boot", "cgb_boot"].map((name) => {
  const bytes = readFileSync(join(sameboy, "build/bin/BootROMs", `${name}.bin`));
  return { name, bytes, sha256: createHash("sha256").update(bytes).digest("hex") };
});
const header = join(work, "include");
mkdirSync(header, { recursive: true });
writeFileSync(
  join(header, "boot_roms.h"),
  `/* Generated by tools/build-sameboy.mjs from SameBoy ${pins.sameboy.tag} BootROMs (Expat). */\n` +
    bootRoms
      .map(({ name, bytes }) => `static const unsigned char ${name}[${bytes.length}] = {${[...bytes].join(",")}};`)
      .join("\n") +
    "\n",
);

// Same sources and switches as SameBoy's libretro build (no debugger,
// cheats, rewind or host time-keeping). Core files need GB_INTERNAL.
const sources = ["gb", "sgb", "apu", "memory", "mbc", "timing", "display", "camera", "sm83_cpu", "joypad", "save_state", "random", "rumble"];
const common = [
  "-std=gnu11", "-O3", "-D_GNU_SOURCE",
  "-DGB_DISABLE_TIMEKEEPING", "-DGB_DISABLE_REWIND", "-DGB_DISABLE_DEBUGGER", "-DGB_DISABLE_CHEATS", "-DGB_DISABLE_CHEAT_SEARCH",
  `-DGB_VERSION="${pins.sameboy.tag.slice(1)}"`, `-DGB_COPYRIGHT_YEAR="2026"`,
  `-I${sameboy}`, `-I${header}`,
  // Deterministic paths in the binary, independent of the runner layout.
  `-ffile-prefix-map=${sameboy}=/sameboy`, `-ffile-prefix-map=${root}=/cartivo`,
];
const objects = join(work, "obj");
rmSync(objects, { recursive: true, force: true });
mkdirSync(objects, { recursive: true });
for (const name of sources)
  run("emcc", [...common, "-DGB_INTERNAL", "-c", join(sameboy, "Core", `${name}.c`), "-o", join(objects, `${name}.o`)], { stdio: "inherit" });
run("emcc", [...common, "-Wall", "-Wextra", "-c", join(core, "src/cartivo.c"), "-o", join(objects, "cartivo.o")], { stdio: "inherit" });

const exports = [
  "malloc", "free", "cartivo_create", "cartivo_free", "cartivo_reset",
  "cartivo_save_size", "cartivo_load_save", "cartivo_save", "cartivo_set_input",
  "cartivo_frames", "cartivo_pixels", "cartivo_audio",
  "cartivo_state_size", "cartivo_save_state", "cartivo_load_state",
];
const out = verify ? mkdtempSync(join(tmpdir(), "sameboy-")) : join(core, "dist");
if (!verify) rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
run("emcc", [
  "-O3", "--no-entry",
  "-sSTANDALONE_WASM=1", "-sFILESYSTEM=0", "-sALLOW_MEMORY_GROWTH=1",
  "-sINITIAL_MEMORY=16MB", "-sSTACK_SIZE=1MB",
  `-sEXPORTED_FUNCTIONS=${exports.map((e) => `_${e}`).join(",")}`,
  ...sources.map((name) => join(objects, `${name}.o`)), join(objects, "cartivo.o"),
  "-o", join(out, "sameboy.wasm"),
], { stdio: "inherit" });
const files = [{ path: "dist/sameboy.wasm", sha256: sha256(join(out, "sameboy.wasm")) }];

if (verify) {
  const manifest = JSON.parse(readFileSync(join(core, "manifest.json"), "utf8"));
  if (JSON.stringify(manifest.files) !== JSON.stringify(files)) {
    console.error("Build no reproducible.\nVersionado:", manifest.files, "\nNuevo:", files);
    process.exit(1);
  }
  console.log("Build reproducible:", files[0].sha256.slice(0, 12));
  process.exit(0);
}

const emscripten = "https://github.com/emscripten-core/emscripten";
const sbom = [
  { name: "SameBoy Core", version: pins.sameboy.tag, license: "MIT", repository: pins.sameboy.repository },
  { name: "SameBoy BootROMs (dmg_boot, cgb_boot)", version: pins.sameboy.tag, license: "MIT", repository: pins.sameboy.repository },
  { name: "Emscripten system libraries", version: pins.emsdk.version, license: "MIT OR NCSA", repository: emscripten },
  { name: "musl libc (Emscripten)", version: pins.emsdk.version, license: "MIT", repository: emscripten },
  { name: "compiler-rt (Emscripten)", version: pins.emsdk.version, license: "Apache-2.0 WITH LLVM-exception", repository: emscripten },
  { name: "dlmalloc (Emscripten)", version: pins.emsdk.version, license: "CC0-1.0", repository: emscripten },
];
writeFileSync(join(core, "sbom.json"), JSON.stringify(sbom, null, 2) + "\n");

const manifest = {
  id: "sameboy-gb-wasm",
  engine: "WebAssembly (standalone)",
  upstream: { name: "SameBoy", ...pins.sameboy },
  toolchain: {
    emcc,
    rgbds: `${pins.rgbds.tag} (${pins.rgbds.commit})`,
    emsdk: `${pins.emsdk.version} (${pins.emsdk.commit})`,
  },
  models: ["DMG-B", "CGB-E"],
  biosRequired: false,
  bootRoms: bootRoms.map(({ name, sha256 }) => ({ name, source: `BootROMs/${name}.asm`, sha256 })),
  patchedFiles: [],
  exports,
  dependencies: sbom.length,
  files,
};
writeFileSync(join(core, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");
console.log(`SameBoy ${pins.sameboy.tag} → ${files.map((f) => `${f.path} ${f.sha256.slice(0, 12)}`).join(", ")}`);
