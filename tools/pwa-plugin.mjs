// Generates the Cartivo service worker at build time. Hand-written on
// purpose: no extra dependency, and the update policy is ours (AGENTS.md:
// an update never reloads an active session nor deletes saves).
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync, statSync } from "node:fs";
import { join, relative, resolve, sep } from "node:path";

export const SW_FILE = "sw.js";
export const CACHE_PREFIX = "cartivo-shell-";
/** Cache entry listing path → content hash, so an update can reuse files. */
export const MANIFEST_PATH = "__cartivo-precache.json";
/**
 * Cross-origin isolation (ADR-020): SharedArrayBuffer, and with it pthreads
 * in cores such as Play! (PS2), needs both headers on every document and
 * worker. Vite's dev and preview servers send them (apps/web/vite.config.ts)
 * and the service worker adds them to everything it serves.
 */
export const ISOLATION_HEADERS = {
  "Cross-Origin-Opener-Policy": "same-origin",
  "Cross-Origin-Embedder-Policy": "require-corp",
};

/** Files that must not be precached. */
export function shouldPrecache(path) {
  return path !== SW_FILE && !path.endsWith(".map") && !path.startsWith(".");
}

/** @param {{ path: string, hash: string }[]} entries */
export function precacheVersion(entries) {
  const h = createHash("sha256");
  for (const e of [...entries].sort((a, b) => a.path.localeCompare(b.path)))
    h.update(`${e.path}\0${e.hash}\n`);
  return h.digest("hex").slice(0, 16);
}

/** @param {{ path: string, hash: string }[]} entries */
export function buildServiceWorker(entries) {
  const version = precacheVersion(entries);
  const files = Object.fromEntries(
    [...entries]
      .sort((a, b) => a.path.localeCompare(b.path))
      .map((e) => [e.path, e.hash]),
  );
  return `// Generated by tools/pwa-plugin.mjs. Do not edit.
const VERSION = ${JSON.stringify(version)};
const CACHE = ${JSON.stringify(CACHE_PREFIX)} + VERSION;
// Every file of the build, cores included: the installed app plays any
// console offline. Value: SHA-256 of the content.
const FILES = ${JSON.stringify(files)};
const MANIFEST = ${JSON.stringify(MANIFEST_PATH)};
// Downloads at a time: the whole catalogue in one burst can stall phones.
const PARALLEL = 6;
const url = (path) => new URL(path, self.registration.scope).href;
const ISOLATION = ${JSON.stringify(ISOLATION_HEADERS)};

/**
 * The response with the cross-origin isolation headers (ADR-020), whatever
 * headers its cached copy was stored with: a copy reused from a version
 * installed before isolation would otherwise serve a worker without COEP to
 * an isolated page, which the browser blocks. Opaque responses pass as is.
 */
function isolated(response) {
  if (response.type === "opaque" || response.type === "opaqueredirect") return response;
  const headers = new Headers(response.headers);
  for (const [name, value] of Object.entries(ISOLATION)) headers.set(name, value);
  return new Response(response.body, { status: response.status, statusText: response.statusText, headers });
}

/** The newest previous Cartivo cache whose manifest says what it holds. */
async function previousCache() {
  const keys = (await caches.keys()).filter(
    (key) => key.startsWith(${JSON.stringify(CACHE_PREFIX)}) && key !== CACHE,
  );
  for (const key of keys.reverse()) {
    const cache = await caches.open(key);
    const listed = await cache.match(url(MANIFEST));
    if (listed) return { cache, hashes: await listed.json() };
  }
  return undefined;
}

/**
 * Stores every file, copying unchanged ones (same path and hash) from the
 * previous version instead of downloading them again: an update only
 * fetches what changed. The manifest is written last, once all files are in:
 * a cache without it is an incomplete install, and a failed install leaves
 * the previous version serving the app.
 */
async function install() {
  const cache = await caches.open(CACHE);
  const previous = await previousCache().catch(() => undefined);
  const queue = Object.entries(FILES);
  const next = async () => {
    for (let item = queue.shift(); item; item = queue.shift()) {
      const [path, hash] = item;
      const reused =
        previous?.hashes[path] === hash
          ? await previous.cache.match(url(path))
          : undefined;
      const response = reused ?? (await fetch(url(path)));
      if (!response.ok) throw new Error("Precache failed: " + path);
      await cache.put(url(path), response);
    }
  };
  await Promise.all(Array.from({ length: PARALLEL }, next));
  await cache.put(url(MANIFEST), new Response(JSON.stringify(FILES)));
}

self.addEventListener("install", (event) => {
  // No skipWaiting here: a new version waits until the app asks for it,
  // which it only does when no game session is active.
  event.waitUntil(install());
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      // Only our own shell caches are removed. IndexedDB saves are never touched.
      // An update only activates from the single open window, which then
      // reloads, so no page is left needing the previous version's assets.
      for (const key of await caches.keys())
        if (key.startsWith(${JSON.stringify(CACHE_PREFIX)}) && key !== CACHE) await caches.delete(key);
      await self.clients.claim();
    })(),
  );
});

self.addEventListener("message", (event) => {
  if (event.data && event.data.type === "cartivo:activate-update") {
    event.waitUntil((async () => {
      const windows = (await self.clients.matchAll({ type: "window", includeUncontrolled: true }))
        .filter((client) => client.url.startsWith(self.registration.scope));
      const accepted = windows.length === 1 && windows[0].id === event.source?.id;
      if (accepted) await self.skipWaiting();
      event.ports?.[0]?.postMessage({ accepted });
    })().catch(() => event.ports?.[0]?.postMessage({ accepted: false })));
  }
  if (event.data && event.data.type === "cartivo:version")
    event.source && event.source.postMessage({ type: "cartivo:version", version: VERSION });
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const target = new URL(request.url);
  if (target.origin !== self.location.origin) return;
  if (request.mode === "navigate") {
    event.respondWith(
      caches.open(CACHE).then(async (cache) =>
        isolated((await cache.match(url("index.html"), { ignoreVary: true })) ?? (await fetch(request))),
      ),
    );
    return;
  }
  // ignoreVary: module scripts and crossorigin styles send Origin, while
  // precached entries were stored without it ("Vary: Origin" would miss).
  event.respondWith(
    caches.open(CACHE).then(async (cache) =>
      isolated((await cache.match(request, { ignoreSearch: true, ignoreVary: true })) ?? (await fetch(request))),
    ),
  );
});
`;
}

function walk(dir, root = dir, out = []) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) walk(full, root, out);
    else out.push(relative(root, full).split(sep).join("/"));
  }
  return out;
}

/** Vite plugin: writes sw.js into the build output after everything else. */
export function cartivoPwa() {
  let outDir = "";
  return {
    name: "cartivo-pwa",
    apply: "build",
    configResolved(config) {
      // outDir is relative to the Vite root (apps/web), not the cwd.
      outDir = resolve(config.root, config.build.outDir);
    },
    closeBundle() {
      const entries = walk(outDir)
        .filter(shouldPrecache)
        .map((path) => ({
          path,
          hash: createHash("sha256")
            .update(readFileSync(join(outDir, path)))
            .digest("hex"),
        }));
      writeFileSync(join(outDir, SW_FILE), buildServiceWorker(entries));
      const bytes = entries.reduce(
        (sum, e) => sum + statSync(join(outDir, e.path)).size,
        0,
      );
      console.log(
        `cartivo-pwa: ${entries.length} archivos precargados, ${(bytes / 1048576).toFixed(1)} MB (todos los núcleos incluidos)`,
      );
    },
  };
}
